export function getGisAsset(key: string): string {
  const normalizedKey = decodeURIComponent(key)
    .replace(/^(\/)?(images\/GIS\/)?/, "")
    .replace(/^(\/)?(src\/assets\/images\/GIS\/)?/, "");
  return (gisAssets as Record<string, string>)[normalizedKey] || (gisAssets as Record<string, string>)[key] || key;
}
